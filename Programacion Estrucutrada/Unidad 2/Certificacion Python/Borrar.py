#Operacion Suma
def suma_mat(n, m):
  # Creamos una nueva matriz vacía con las mismas dimensiones que 'n'
  filas = len(n)
  columnas = len(n[0])
  # Expansion de tabla dinamicamente
  resultado_suma = [[0 for _ in range(columnas)] for _ in range(filas)]
  #resultado_suma = [[0,0],[0,0]]

  for fila in range(filas):
    for columna in range(columnas):
      resultado_suma[fila][columna] = n[fila][columna] + m[fila][columna]

  return resultado_suma
