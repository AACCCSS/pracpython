#Operacion multiplicacion
def multiplicacion_mat(n, m):
  filas_n = len(n)
  columnas_n = len(n[0])
  columnas_m = len(m[0])

  resultado_op = [[0 for _ in range(columnas_m)] for _ in range(filas_n)]

  for i in range(filas_n):
    for j in range(columnas_m):
      for k in range(columnas_n):
        resultado_op[i][j] += n[i][k] * m[k][j]

  return resultado_op
